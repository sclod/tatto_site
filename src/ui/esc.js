// Экранирование для подстановки текста в HTML-шаблоны (innerHTML).
// Данные сейчас наши собственные, но название работы с кавычкой не должно ломать разметку.
const MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
export const esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => MAP[c]);
